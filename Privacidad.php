    <h1>AVISO DE PRIVACIDAD</h1>

    <p>
        En cumplimiento con la Ley Federal de Protección de Datos Personales en Posesión de los Particulares,
        informamos a los usuarios de la plataforma de Parques y Plazas de Nuevo León que los datos personales
        proporcionados serán tratados de manera confidencial y utilizados únicamente para los fines descritos
        en el presente aviso.
    </p>

    <h2>Datos personales recabados</h2>

    <p>Para el registro y acceso a la plataforma, se podrán solicitar los siguientes datos:</p>

    <ul>
        <li>Nombre de usuario.</li>
        <li>Correo electrónico.</li>
        <li>Contraseña.</li>
    </ul>

    <h2>Finalidad del tratamiento de los datos</h2>

    <p>Los datos personales recabados serán utilizados para:</p>

    <ul>
        <li>Crear y administrar cuentas de usuario.</li>
        <li>Permitir el acceso a las funciones de la plataforma.</li>
        <li>Identificar a los usuarios que publiquen información sobre parques y plazas.</li>
        <li>Mantener la seguridad y correcto funcionamiento del sistema.</li>
        <li>Enviar notificaciones relacionadas con la cuenta cuando sea necesario.</li>
    </ul>

    <h2>Protección de la información paps</h2>

    <p>
        La seguridad de los datos personales es una prioridad para esta plataforma.
        Las contraseñas de los usuarios no se almacenan en texto plano, sino mediante
        técnicas de cifrado unidireccional (hash), lo que contribuye a proteger la
        información contra accesos no autorizados.
    </p>

    <p>
        Asimismo, se implementan medidas de seguridad técnicas y administrativas para
        resguardar los datos personales almacenados.
    </p>

    <h2>Compartición de datos</h2>

    <p>
        La información personal de los usuarios no será vendida, alquilada ni compartida
        con terceros, salvo cuando exista una obligación legal que así lo requiera.
    </p>

    <h2>Derechos ARCO</h2>

    <p>
        Los usuarios tienen derecho a Acceder, Rectificar, Cancelar u Oponerse al
        tratamiento de sus datos personales (Derechos ARCO), mediante una solicitud
        realizada a los administradores de la plataforma.
    </p>

    <h2>Modificaciones al aviso de privacidad</h2>

    <p>
        Este aviso de privacidad podrá ser actualizado cuando sea necesario.
        Cualquier modificación será publicada dentro de la plataforma para conocimiento
        de los usuarios.
    </p>

    <h2>Contacto</h2>

    <p>
        Si tiene dudas sobre el tratamiento de sus datos personales o desea ejercer sus
        Derechos ARCO, puede comunicarse con los administradores de la plataforma a través
        del correo electrónico de contacto proporcionado en el sitio web.
    </p>
    

